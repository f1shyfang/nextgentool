import { randomUUID } from "node:crypto";
import postgres from "postgres";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { createPipelineService } from "../application/service";
import type { Deal, PipelineContext } from "../domain/pipeline";
import type { PipelineRepository } from "../domain/ports";

// Opt in explicitly: ordinary unit-test runs never connect to a developer database.
const optedIn = process.env.PIPELINE_INTEGRATION_TEST === "true";
describe.skipIf(!optedIn)("Deal Pipeline PostgreSQL integration", () => {
  let sql: ReturnType<typeof postgres>;
  let repository: PipelineRepository;
  let service: ReturnType<typeof createPipelineService>;
  const researchFirmId = randomUUID();
  const foreignResearchFirmId = randomUUID();
  const companyId = randomUUID();
  const foreignCompanyId = randomUUID();
  const longName = `E2E canonical ${"x".repeat(186)}`;
  let canonicalService: ReturnType<typeof createPipelineService>;
  let lookup: import("../domain/ports").CompanyLookup;
  let companyRepository: ReturnType<
    typeof import("../../company-intelligence/infrastructure/repository").createCompanyRepository
  >;
  const firmId = randomUUID();
  const otherFirmId = randomUUID();
  const memberId = randomUUID();
  const ownerId = randomUUID();
  const otherMemberId = randomUUID();
  const context: PipelineContext = { firmId, memberId };
  const otherContext: PipelineContext = {
    firmId: otherFirmId,
    memberId: otherMemberId,
  };
  const clerkId = `e2e_integration_${randomUUID()}`;
  const request = () => randomUUID();
  const create = (input: Record<string, unknown> = {}) =>
    service.create(context, {
      requestId: request(),
      companyName: "E2E integration company",
      ...input,
    });
  const eventsFor = async (deal: Deal) =>
    (await service.detail(context, deal.id)).events;

  beforeAll(async () => {
    const url = new URL(process.env.DATABASE_URL ?? "");
    expect(url.protocol).toMatch(/^postgres(?:ql)?:$/);
    expect(url.hostname).toBe("localhost");
    expect(url.pathname).toBe("/nextgentool_pipeline");
    expect(url.port || "5432").toBe("5432");
    sql = postgres(url.toString());
    const [identity] = await sql`select current_database() as name`;
    expect(identity.name).toBe("nextgentool_pipeline");
    repository = (
      await import("./drizzle-pipeline-repository")
    ).createDrizzlePipelineRepository();
    service = createPipelineService(repository, {
      search: async () => [],
      resolve: async () => null,
    });
    await sql`insert into research_firms (id, name) values (${researchFirmId}, 'E2E canonical research'), (${foreignResearchFirmId}, 'E2E foreign research')`;
    await sql`insert into research_memberships (user_id, firm_id, role) values (${clerkId}, ${researchFirmId}, 'viewer')`;
    const now = new Date().toISOString();
    await sql`insert into intelligence_companies (id, firm_id, name, domain, created_at, updated_at) values
      (${companyId}, ${researchFirmId}, ${longName}, 'canonical-e2e.example.com', ${now}, ${now}),
      (${foreignCompanyId}, ${foreignResearchFirmId}, 'E2E hidden canonical', null, ${now}, ${now})`;
    companyRepository = (
      await import("../../company-intelligence/infrastructure/repository")
    ).createCompanyRepository(url.toString());
    const companyService = (
      await import("../../company-intelligence/application/service")
    ).createCompanyService({
      repository: companyRepository,
      clock: { id: randomUUID, now: () => new Date().toISOString() },
    });
    lookup = (await import("./company-lookup")).createCompanyIntelligenceLookup(
      companyService,
    );
    canonicalService = createPipelineService(repository, lookup);
    await sql`insert into pipeline_firms (id, name) values
      (${firmId}, 'E2E integration firm'),
      (${otherFirmId}, 'E2E integration other firm')`;
    await sql`insert into pipeline_members (id, firm_id, clerk_user_id, name) values
      (${memberId}, ${firmId}, ${clerkId}, 'E2E integration actor'),
      (${ownerId}, ${firmId}, ${`${clerkId}_owner`}, 'E2E integration owner'),
      (${otherMemberId}, ${otherFirmId}, ${`${clerkId}_other`}, 'E2E integration other actor')`;
    await sql`update pipeline_firms set research_firm_id = ${researchFirmId} where id = ${firmId}`;
  });

  afterAll(async () => {
    if (!sql) return;
    try {
      // Every predicate uses only UUIDs generated by this suite, never user fixtures.
      await sql.begin(async (tx) => {
        await tx`delete from pipeline_requests where firm_id in (${firmId}, ${otherFirmId})`;
        await tx`delete from pipeline_events where firm_id in (${firmId}, ${otherFirmId})`;
        await tx`delete from pipeline_deals where firm_id in (${firmId}, ${otherFirmId})`;
        await tx`delete from pipeline_members where firm_id in (${firmId}, ${otherFirmId})`;
        await tx`delete from pipeline_firms where id in (${firmId}, ${otherFirmId})`;
        await tx`delete from intelligence_companies where firm_id in (${researchFirmId}, ${foreignResearchFirmId})`;
        await tx`delete from research_memberships where user_id = ${clerkId}`;
        await tx`delete from research_firms where id in (${researchFirmId}, ${foreignResearchFirmId})`;
      });
    } finally {
      await companyRepository?.close();
      await sql.end();
    }
  });

  it("creates a deal, its initial event, and retry result together", async () => {
    const requestId = request();
    const deal = await create({ requestId });
    expect(deal).toMatchObject({
      firmId,
      ownerId: memberId,
      stage: "inbox",
      version: 1,
    });
    expect(await eventsFor(deal)).toEqual([
      expect.objectContaining({
        kind: "created",
        actorId: memberId,
        fromStage: null,
        toStage: "inbox",
      }),
    ]);
    const [saved] = await sql`select result from pipeline_requests
      where firm_id = ${firmId} and actor_id = ${memberId} and request_id = ${requestId}`;
    expect(saved.result).toEqual(deal);
  });

  it("rolls back deal and event writes when a transaction fails", async () => {
    const source = await create();
    const id = randomUUID();
    const requestId = request();
    await expect(
      repository.mutate(context, requestId, "rollback-fixture", async (tx) => {
        await tx.insertDeal({ ...source, id });
        await tx.appendEvent({
          id: randomUUID(),
          dealId: id,
          actorId: memberId,
          occurredAt: source.createdAt,
          kind: "created",
          fromStage: null,
          toStage: "inbox",
          rationale: "",
          changes: {},
        });
        throw new Error("E2E integration intentional rollback");
      }),
    ).rejects.toThrow("intentional rollback");
    expect(
      await sql`select id from pipeline_deals where id = ${id}`,
    ).toHaveLength(0);
    expect(
      await sql`select id from pipeline_events where deal_id = ${id}`,
    ).toHaveLength(0);
    expect(
      await sql`select request_id from pipeline_requests where firm_id = ${firmId} and request_id = ${requestId}`,
    ).toHaveLength(0);
  });

  it("deduplicates sequential and simultaneous create retries", async () => {
    const input = {
      requestId: request(),
      companyName: "E2E integration retry",
    };
    const results = await Promise.all(
      Array.from({ length: 4 }, () => service.create(context, input)),
    );
    results.push(await service.create(context, input));
    expect(new Set(results.map((deal) => deal.id)).size).toBe(1);
    for (const deal of results) expect(deal).toEqual(results[0]);
    expect(await eventsFor(results[0])).toHaveLength(1);
  });

  it("rejects a reused request ID with a changed payload", async () => {
    const requestId = request();
    const deal = await create({ requestId });
    await expect(
      create({ requestId, companyName: "E2E integration changed" }),
    ).rejects.toMatchObject({ code: "conflict" });
    expect(await eventsFor(deal)).toHaveLength(1);
  });

  it("preserves omitted fields and an unchanged disabled owner on PATCH", async () => {
    const deal = await create({
      ownerId,
      nextStep: "Call founder",
      summary: "Existing summary",
      dueDate: "2026-12-31",
    });
    await sql`update pipeline_members set enabled = false where id = ${ownerId} and firm_id = ${firmId}`;
    try {
      const updated = await service.update(context, deal.id, {
        requestId: request(),
        expectedVersion: 1,
        name: "E2E integration renamed",
        ownerId,
      });
      expect(updated).toMatchObject({
        ownerId,
        nextStep: deal.nextStep,
        summary: deal.summary,
        dueDate: deal.dueDate,
        companyName: deal.companyName,
        version: 2,
      });
      expect((await eventsFor(deal))[1].changes).toEqual({
        name: { before: deal.name, after: updated.name },
      });
    } finally {
      await sql`update pipeline_members set enabled = true where id = ${ownerId} and firm_id = ${firmId}`;
    }
  });

  it("allows only one writer for a shared expected version", async () => {
    const deal = await create();
    const results = await Promise.allSettled(
      ["one", "two"].map((summary) =>
        service.update(context, deal.id, {
          requestId: request(),
          expectedVersion: 1,
          summary,
        }),
      ),
    );
    expect(
      results.filter((result) => result.status === "fulfilled"),
    ).toHaveLength(1);
    const rejected = results.find((result) => result.status === "rejected");
    expect(rejected?.status === "rejected" && rejected.reason).toMatchObject({
      code: "conflict",
    });
    const detail = await service.detail(context, deal.id);
    expect(detail.deal.version).toBe(2);
    expect(detail.events).toHaveLength(2);
  });

  it("preserves stage entry and deterministic board ordering during material edits", async () => {
    const companyName = `E2E integration ordering ${randomUUID()}`;
    const oldest = await create({ companyName });
    const tied = await Promise.all([
      create({ companyName }),
      create({ companyName }),
    ]);
    await sql`update pipeline_deals set stage_entered_at = '2020-01-01T00:00:00Z'
      where firm_id = ${firmId} and id = ${oldest.id}`;
    for (const deal of tied) {
      await sql`update pipeline_deals set stage_entered_at = '2021-01-01T00:00:00Z'
        where firm_id = ${firmId} and id = ${deal.id}`;
    }
    const expectedOrder = [...tied.map((deal) => deal.id).sort(), oldest.id];
    const board = () =>
      service.list(context, { q: companyName, stage: "inbox" });
    expect((await board()).deals.map((deal) => deal.id)).toEqual(expectedOrder);
    const before = (await service.detail(context, oldest.id)).deal;
    const updated = await service.update(context, oldest.id, {
      requestId: request(),
      expectedVersion: 1,
      summary: "A material edit",
    });
    expect(updated.stageEnteredAt).toBe(before.stageEnteredAt);
    expect(updated.stage).toBe("inbox");
    expect(updated.version).toBe(2);
    expect((await board()).deals.map((deal) => deal.id)).toEqual(expectedOrder);
    const moved = await service.transition(context, oldest.id, {
      requestId: request(),
      expectedVersion: 2,
      stage: "screening",
    });
    expect(new Date(moved.stageEnteredAt).getTime()).toBeGreaterThan(
      new Date(before.stageEnteredAt).getTime(),
    );
    expect((await board()).deals.map((deal) => deal.id)).toEqual(
      expectedOrder.slice(0, 2),
    );
    const returned = await service.transition(context, oldest.id, {
      requestId: request(),
      expectedVersion: 3,
      stage: "inbox",
    });
    expect(returned.version).toBe(4);
    expect((await board()).deals.map((deal) => deal.id)).toEqual([
      oldest.id,
      ...expectedOrder.slice(0, 2),
    ]);
  });

  it("keeps an unchanged PATCH free of extra versions and events", async () => {
    const created = await create({
      summary: "Same summary",
      nextStep: "Same action",
      dueDate: "2026-12-31",
    });
    const before = await service.detail(context, created.id);
    const result = await service.update(context, created.id, {
      requestId: request(),
      expectedVersion: 1,
      name: created.name,
      ownerId: created.ownerId,
      summary: created.summary,
      nextStep: created.nextStep,
      dueDate: created.dueDate,
    });
    expect(result).toEqual(before.deal);
    expect(await service.detail(context, created.id)).toEqual(before);
  });

  it("keeps no-op stage moves free of extra versions and events", async () => {
    const deal = await create();
    const result = await service.transition(context, deal.id, {
      requestId: request(),
      expectedVersion: 1,
      stage: "inbox",
    });
    expect(result.version).toBe(1);
    expect(await eventsFor(deal)).toHaveLength(1);
  });

  it("records close/reopen rationale and requires closing confirmation", async () => {
    const deal = await create();
    await expect(
      service.transition(context, deal.id, {
        requestId: request(),
        expectedVersion: 1,
        stage: "passed",
      }),
    ).rejects.toMatchObject({ code: "invalid" });
    const closed = await service.transition(context, deal.id, {
      requestId: request(),
      expectedVersion: 1,
      stage: "passed",
      confirmed: true,
      rationale: "Outside mandate",
    });
    await expect(
      service.transition(context, deal.id, {
        requestId: request(),
        expectedVersion: 2,
        stage: "invested",
        confirmed: true,
      }),
    ).rejects.toMatchObject({ code: "invalid" });
    const reopened = await service.transition(context, deal.id, {
      requestId: request(),
      expectedVersion: closed.version,
      stage: "screening",
      rationale: "Mandate changed",
    });
    expect(reopened.version).toBe(3);
    expect(await eventsFor(deal)).toEqual([
      expect.objectContaining({ kind: "created" }),
      expect.objectContaining({
        kind: "closed",
        fromStage: "inbox",
        toStage: "passed",
        rationale: "Outside mandate",
      }),
      expect.objectContaining({
        kind: "reopened",
        fromStage: "passed",
        toStage: "screening",
        rationale: "Mandate changed",
      }),
    ]);
  });

  it("rejects invalid dates, stages, and foreign owners without changing data", async () => {
    const deal = await create();
    for (const dueDate of ["2026-02-30", "not-a-date", "2026-13-01"]) {
      await expect(create({ dueDate })).rejects.toMatchObject({
        code: "invalid",
      });
      await expect(
        service.update(context, deal.id, {
          requestId: request(),
          expectedVersion: 1,
          dueDate,
        }),
      ).rejects.toMatchObject({ code: "invalid" });
    }
    await expect(create({ stage: "unknown" })).rejects.toMatchObject({
      code: "invalid",
    });
    await expect(
      service.transition(context, deal.id, {
        requestId: request(),
        expectedVersion: 1,
        stage: "unknown",
      }),
    ).rejects.toMatchObject({ code: "invalid" });
    await expect(create({ ownerId: otherMemberId })).rejects.toMatchObject({
      code: "invalid",
    });
    await expect(
      service.update(context, deal.id, {
        requestId: request(),
        expectedVersion: 1,
        ownerId: otherMemberId,
      }),
    ).rejects.toMatchObject({ code: "invalid" });
    expect(await eventsFor(deal)).toHaveLength(1);
  });

  it("isolates list, detail, members, and mutations across firms", async () => {
    const deal = await create();
    const otherDeal = await service.create(otherContext, {
      requestId: request(),
      companyName: "E2E integration private other company",
    });
    const list = await service.list(otherContext, { scope: "all" });
    expect(list.deals.map((item) => item.id)).toEqual([otherDeal.id]);
    expect(
      (await service.members(otherContext)).map((member) => member.id),
    ).toEqual([otherMemberId]);
    await expect(service.detail(otherContext, deal.id)).rejects.toMatchObject({
      code: "not_found",
    });
    await expect(
      service.update(otherContext, deal.id, {
        requestId: request(),
        expectedVersion: 1,
        summary: "forged",
      }),
    ).rejects.toMatchObject({ code: "not_found" });
    await expect(
      service.transition(otherContext, deal.id, {
        requestId: request(),
        expectedVersion: 1,
        stage: "screening",
      }),
    ).rejects.toMatchObject({ code: "not_found" });
    await expect(
      service.list({ firmId, memberId: otherMemberId }),
    ).rejects.toMatchObject({ code: "forbidden" });
    expect(await eventsFor(deal)).toHaveLength(1);
  });

  it("denies disabled actors reads, writes, and cached mutation replays", async () => {
    const requestId = request();
    const deal = await create({ requestId });
    await sql`update pipeline_members set enabled = false where id = ${memberId} and firm_id = ${firmId}`;
    try {
      expect(await repository.memberForUser(clerkId)).toBeNull();
      for (const operation of [
        () => service.list(context),
        () => service.detail(context, deal.id),
        () => service.members(context),
        () => create(),
        () => create({ requestId }),
        () =>
          service.update(context, deal.id, {
            requestId: request(),
            expectedVersion: 1,
            summary: "Denied",
          }),
        () =>
          service.transition(context, deal.id, {
            requestId: request(),
            expectedVersion: 1,
            stage: "screening",
          }),
      ])
        await expect(operation()).rejects.toMatchObject({ code: "forbidden" });
    } finally {
      await sql`update pipeline_members set enabled = true where id = ${memberId} and firm_id = ${firmId}`;
    }
    expect(await eventsFor(deal)).toHaveLength(1);
  });
  it("searches canonical names and domains with viewer membership and resolves authoritative 200-character names", async () => {
    expect(longName).toHaveLength(200);
    const matches = await lookup.search(context, "canonical-e2e.example.com");
    expect(matches).toEqual([
      { id: companyId, name: longName, href: `/companies/${companyId}/` },
    ]);
    expect(await lookup.search(context, "E2E hidden canonical")).toEqual([]);
    const linked = await canonicalService.create(context, {
      requestId: request(),
      companyId,
      companyName: "Tampered name",
    });
    expect(linked).toMatchObject({
      companyId,
      companyName: longName,
      name: longName,
      companyHref: `/companies/${companyId}/`,
    });
    expect(
      (await canonicalService.detail(context, linked.id)).deal.companyId,
    ).toBe(companyId);
  });

  it("links a provisional deal then unlinks it with audited canonical identity changes", async () => {
    const provisional = await create();
    const linked = await canonicalService.update(context, provisional.id, {
      requestId: request(),
      expectedVersion: 1,
      companyId,
    });
    expect(linked.companyName).toBe(longName);
    const history = await canonicalService.detail(context, linked.id);
    expect(
      history.events.some(
        (event) => event.changes.companyId?.after === companyId,
      ),
    ).toBe(true);
    const unlinked = await canonicalService.update(context, linked.id, {
      requestId: request(),
      expectedVersion: 2,
      companyId: null,
      companyName: "E2E provisional again",
    });
    expect(unlinked).toMatchObject({
      companyId: null,
      companyHref: null,
      companyName: "E2E provisional again",
    });
  });

  it("rejects foreign canonical identities without leaking profile data", async () => {
    expect(await lookup.resolve(context, foreignCompanyId)).toBeNull();
    await expect(
      canonicalService.create(context, {
        requestId: request(),
        companyId: foreignCompanyId,
      }),
    ).rejects.toMatchObject({ code: "not_found" });
  });

  it("requires an explicit firm mapping and matching research membership", async () => {
    await expect(lookup.search(otherContext, "E2E")).rejects.toMatchObject({
      code: "forbidden",
    });
    await sql`update research_memberships set firm_id = ${foreignResearchFirmId} where user_id = ${clerkId}`;
    try {
      await expect(lookup.search(context, "E2E")).rejects.toMatchObject({
        code: "forbidden",
      });
    } finally {
      await sql`update research_memberships set firm_id = ${researchFirmId} where user_id = ${clerkId}`;
    }
  });

  it("rechecks membership after search, while provisional pipeline capture still works", async () => {
    await lookup.search(context, "canonical-e2e");
    await sql`delete from research_memberships where user_id = ${clerkId}`;
    try {
      await expect(
        canonicalService.create(context, { requestId: request(), companyId }),
      ).rejects.toMatchObject({ code: "forbidden" });
      const provisional = await canonicalService.create(context, {
        requestId: request(),
        companyName: "E2E still provisional",
      });
      expect(provisional.companyId).toBeNull();
    } finally {
      await sql`insert into research_memberships (user_id, firm_id, role) values (${clerkId}, ${researchFirmId}, 'viewer')`;
    }
  });
});
